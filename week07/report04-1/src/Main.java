// Report 1 : 증가(++), 감소(--) 연산자의 실행 결과
// 전위(++a, --a) : 값을 먼저 바꾼 뒤 사용 / 후위(a++, a--) : 현재 값을 사용한 뒤 바꿈
// ※ 문제의 "a = 3, b = 4;" 는 Java 문법상 오류이므로 "a = 3; b = 4;" 로 작성
void main() {
    int a, b, c;

    // (1) c = --a + b--;
    a = 3; b = 4;
    c = --a + b--;          // a: 3 -> 2 후 사용(2), b: 4 사용 후 3  =>  c = 2 + 4 = 6
    System.out.printf("(1) a = %d, b = %d, c = %d\n", a, b, c);

    // (2) c = a-- + ++b;
    a = 3; b = 4;
    c = a-- + ++b;          // a: 3 사용 후 2, b: 4 -> 5 후 사용(5)  =>  c = 3 + 5 = 8
    System.out.printf("(2) a = %d, b = %d, c = %d\n", a, b, c);
}
